export function getSimplifiedPronunciation(word) {
  const cleaned = cleanWord(word);
  if (!cleaned) return "";
  if (simplifiedPronunciations.has(cleaned)) return simplifiedPronunciations.get(cleaned);

  let pron = cleaned;

  // Consonant patterns (applied before vowel work)
  pron = pron.replace(/ph/gi, "f");
  pron = pron.replace(/^kn/gi, "n");
  pron = pron.replace(/^ps/gi, "s");
  pron = pron.replace(/^wr/gi, "r");
  pron = pron.replace(/ck\b/gi, "k");

  // Vowel digraphs
  pron = pron.replace(/igh/gi, "ai");
  pron = pron.replace(/ee/gi, "íi");
  pron = pron.replace(/ea/gi, "íi");
  pron = pron.replace(/oa/gi, "ou");
  pron = pron.replace(/oo/gi, "u");
  pron = pron.replace(/ai/gi, "ei");
  pron = pron.replace(/ay\b/gi, "ei");
  pron = pron.replace(/oy\b/gi, "oi");
  pron = pron.replace(/oi/gi, "oi");
  pron = pron.replace(/ou/gi, "au");
  pron = pron.replace(/ow\b/gi, "au");
  pron = pron.replace(/aw/gi, "o");
  pron = pron.replace(/au/gi, "o");
  pron = pron.replace(/er\b/gi, "er");
  pron = pron.replace(/or\b/gi, "or");
  pron = pron.replace(/ar\b/gi, "ar");

  // Consonant substitutions for Spanish speakers
  pron = pron.replace(/th/gi, "z");
  pron = pron.replace(/sh/gi, "sh");
  pron = pron.replace(/ch/gi, "ch");
  pron = pron.replace(/j/gi, "y");
  pron = pron.replace(/w/gi, "u");

  // Common endings
  pron = pron.replace(/tion\b/gi, "shon");
  pron = pron.replace(/sion\b/gi, "yon");
  pron = pron.replace(/ture\b/gi, "chur");
  pron = pron.replace(/sure\b/gi, "yur");
  pron = pron.replace(/cial\b/gi, "shal");
  pron = pron.replace(/tial\b/gi, "shal");
  pron = pron.replace(/cious\b/gi, "shos");
  pron = pron.replace(/ble\b/gi, "bl");
  pron = pron.replace(/ple\b/gi, "pl");
  pron = pron.replace(/dle\b/gi, "dl");
  pron = pron.replace(/gle\b/gi, "gl");
  pron = pron.replace(/tle\b/gi, "tl");
  pron = pron.replace(/cle\b/gi, "kl");

  // Silent e removal
  pron = pron.replace(/e$/i, "");

  return pron;
}

export function analyzeByWordSimilarity(expectedWords, transcriptWords) {
  const cleanedTranscript = transcriptWords.map(cleanWord).filter(Boolean);
  let transcriptIndex = 0;

  return expectedWords.map((rawWord, index) => {
    const expected = cleanWord(rawWord);
    const heard = cleanedTranscript[transcriptIndex] || "";
    const score = similarity(expected, heard);
    const correct = expected && score >= 0.76;

    if (correct || score >= 0.45) transcriptIndex += 1;

    return {
      index,
      word: rawWord,
      expected,
      heard,
      score: Number(score.toFixed(2)),
      status: correct ? "correct" : "incorrect",
      phonemeHints: correct ? [] : getErrorHints(expected, heard)
    };
  });
}

function similarity(a, b) {
  if (!a || !b) return 0;
  if (a === b) return 1;
  const distance = levenshtein(a, b);
  return Math.max(0, 1 - distance / Math.max(a.length, b.length));
}

function levenshtein(a, b) {
  const matrix = Array.from({ length: a.length + 1 }, () => Array(b.length + 1).fill(0));
  for (let i = 0; i <= a.length; i++) matrix[i][0] = i;
  for (let j = 0; j <= b.length; j++) matrix[0][j] = j;

  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      matrix[i][j] = Math.min(
        matrix[i - 1][j] + 1,
        matrix[i][j - 1] + 1,
        matrix[i - 1][j - 1] + cost
      );
    }
  }
  return matrix[a.length][b.length];
}

function getErrorHints(expected, heard) {
  if (!heard) return ["No detectado por el reconocimiento de voz"];
  const hints = [];
  if (expected.includes("th") && !heard.includes("th")) hints.push("Revisar /θ/ o /ð/");
  if (expected.includes("r") && !heard.includes("r")) hints.push("Revisar sonido /r/ inglesa");
  if (expected.includes("v") && heard.includes("b")) hints.push("Diferenciar /v/ y /b/");
  if (Math.abs(expected.length - heard.length) >= 3) hints.push("Duración o sílabas distintas");
  if (!hints.length) hints.push("Diferencia detectada en sonidos o acento");
  return hints;
}
