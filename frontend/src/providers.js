export function getWords(text) {
  return text
    .replace(/[“”]/g, '"')
    .replace(/[’]/g, "'")
    .split(/\s+/)
    .map((word) => word.trim())
    .filter(Boolean);
}

export function cleanWord(word) {
  return word.toLowerCase().replace(/^[^a-z']+|[^a-z']+$/gi, "");
}

